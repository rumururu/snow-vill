const showcaseVillageId = 'showcase';

Map<String, Object?> showcaseVillageJson(String lang) {
  final names = nicknames[lang]!;
  final created = DateTime.utc(2026, 11, 20);
  return {
    'id': showcaseVillageId,
    'name': villageName[lang],
    'created_at': created.toIso8601String(),
    'capacity': 6,
    'open_halves': 3, // the free village: district 0, both halves
    'path_style': 'dirt',
    'decor': <String, Object?>{},
    'houses': [
      for (var slot = 0; slot < 5; slot++)
        {
          'id': 'h$slot',
          'slot': slot,
          'nickname': names[slot],
          'style': _styles[(slot * 4 + slot ~/ 9) % _styles.length],
          'direction': (slot * 3) % 4,
          'message': photoSlots.contains(slot)
              ? messages[lang]![photoSlots.indexOf(slot)]
              : '',
          'has_photo': photoSlots.contains(slot),
          'created_at': created
              .add(Duration(hours: slot * 7))
              .toIso8601String(),
        },
    ],
  };
}
